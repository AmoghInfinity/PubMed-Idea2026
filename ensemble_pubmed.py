#Weighted Word2Vec Ensemble
import numpy as np
import torch
from sklearn.metrics import accuracy_score, f1_score, precision_score, roc_auc_score
from scipy.optimize import minimize

# List of prediction arrays from models
word2vec_preds = [
    CNN_Word2Vec_preds,
    RNN_Word2Vec_preds,
    LSTM_Word2Vec_preds,
    BiLSTM_Word2Vec_preds,
    GRU_Word2Vec_preds,
    BiGRU_Word2Vec_preds
]

# Convert to numpy array of shape (n_models, n_samples, n_classes)
preds_array = np.array(word2vec_preds)
n_models = preds_array.shape[0]

# Convert true labels to tensor
y_true_tensor = torch.tensor(y_true).float().double()

# Define BCE loss function
criterion = torch.nn.BCELoss()

# Loss function to minimize (with normalized weights)
def loss_fn(weights):
    weights = np.array(weights)
    weights = weights / weights.sum()  # Normalize weights
    weighted_preds = np.tensordot(weights, preds_array, axes=(0, 0))  # shape: (n_samples, n_classes)
    # Convert weighted_preds to tensor and ensure it's float64 (Double)
    pred_tensor = torch.tensor(weighted_preds).double()
    loss = criterion(pred_tensor, y_true_tensor)
    return loss.item()

# Initial weights (equal)
init_weights = np.ones(n_models) / n_models

# Constraint: weights sum to 1
constraints = ({'type': 'eq', 'fun': lambda w: np.sum(w) - 1})

# Bounds: weights between 0 and 1
bounds = [(0.0, 1.0)] * n_models

# Optimize weights
result = minimize(loss_fn, init_weights, method='SLSQP', bounds=bounds, constraints=constraints)

# Get optimal weights
optimal_weights = result.x
print(f"Optimal Weights: {optimal_weights}")

# Compute final weighted predictions
ensemble_preds = np.tensordot(optimal_weights, preds_array, axes=(0, 0))
mean_pred = np.mean(ensemble_preds)

# Threshold predictions
threshold = 0.5
y_pred_bin = (ensemble_preds >= threshold).astype(int)

# Compute metrics
