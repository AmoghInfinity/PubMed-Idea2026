precision = precision_score(y_true, y_pred_bin, average='micro')
auc = roc_auc_score(y_true, ensemble_preds, average='macro')

# BCE Loss
ensemble_preds_tensor = torch.tensor(ensemble_preds).double() # Ensure this is also double
loss = criterion(ensemble_preds_tensor, y_true_tensor)

# Output
print(f"\nWeighted Ensemble Metrics (Optimized):")
print(f"Mean Prediction: {mean_pred:.4f}")
print(f"Loss: {loss.item():.4f}")
print(f"Accuracy: {accuracy:.4f}")
